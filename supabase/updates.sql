-- Versiones publicadas para la autoactualización del POS.
-- Ejecutar una vez en Supabase > SQL Editor.
--
-- El instalador debe estar en una URL directa, por ejemplo un bucket público
-- "releases" de Supabase Storage o un asset de GitHub Releases.

create table if not exists public.app_releases (
    id bigint generated by default as identity primary key,
    version text not null,
    download_url text not null,
    sha256 text not null,
    notes text not null default '',
    mandatory boolean not null default false,
    min_supported_version text,
    created_at timestamptz not null default now()
);

create index if not exists app_releases_created_at_idx
    on public.app_releases (created_at desc);

alter table public.app_releases enable row level security;

drop policy if exists "app_releases_read" on public.app_releases;
create policy "app_releases_read"
    on public.app_releases
    for select
    using (true);

grant select on public.app_releases to anon, authenticated;

