create table if not exists public.products (
    id bigint generated by default as identity primary key,
    barcode text unique,
    code text,
    name text not null,
    price numeric(12, 2) not null default 0,
    price_wholesale numeric(12, 2) not null default 0,
    unit text not null default 'U',
    stock numeric(12, 3) not null default 0,
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists products_code_idx on public.products (lower(code));
create index if not exists products_name_idx on public.products (lower(name));

create sequence if not exists public.ticket_number_seq start 1;

create table if not exists public.sales (
    id bigint generated by default as identity primary key,
    ticket_number bigint not null default nextval('public.ticket_number_seq'),
    total numeric(12, 2) not null default 0,
    payment_method text not null default 'Efectivo',
    amount_received numeric(12, 2),
    change_amount numeric(12, 2),
    user_name text not null default 'ALKIMIA',
    created_at timestamptz not null default now()
);

create table if not exists public.sale_items (
    id bigint generated by default as identity primary key,
    sale_id bigint not null references public.sales(id) on delete cascade,
    product_id bigint references public.products(id) on delete set null,
    code text,
    name text not null,
    unit text,
    price numeric(12, 2) not null,
    qty numeric(12, 3) not null,
    subtotal numeric(12, 2) not null,
    mode text not null default 'normal'
);

create table if not exists public.cash_cuts (
    id bigint generated by default as identity primary key,
    total numeric(12, 2) not null default 0,
    tickets integer not null default 0,
    details text,
    user_name text,
    created_at timestamptz not null default now()
);

create table if not exists public.settings (
    key text primary key,
    value text not null default ''
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at
before update on public.products
for each row execute function public.set_updated_at();

create or replace function public.register_sale(
    p_items jsonb,
    p_payment_method text default 'Efectivo',
    p_amount_received numeric default null,
    p_change_amount numeric default null,
    p_user_name text default 'ALKIMIA'
)
returns public.sales
language plpgsql
security definer
set search_path = public
as $$
declare
    v_sale public.sales;
    v_item jsonb;
    v_qty numeric(12, 3);
    v_price numeric(12, 2);
    v_subtotal numeric(12, 2);
    v_total numeric(12, 2) := 0;
    v_product_id bigint;
begin
    if p_items is null or jsonb_array_length(p_items) = 0 then
        raise exception 'El ticket esta vacio';
    end if;

    for v_item in select * from jsonb_array_elements(p_items) loop
        v_qty := (v_item ->> 'qty')::numeric;
        v_price := (v_item ->> 'price')::numeric;
        v_total := v_total + round(v_qty * v_price, 2);
    end loop;

    insert into public.sales (total, payment_method, amount_received, change_amount, user_name)
    values (
        v_total,
        coalesce(p_payment_method, 'Efectivo'),
        p_amount_received,
        p_change_amount,
        coalesce(p_user_name, 'ALKIMIA')
    )
    returning * into v_sale;

    for v_item in select * from jsonb_array_elements(p_items) loop
        v_qty := (v_item ->> 'qty')::numeric;
        v_price := (v_item ->> 'price')::numeric;
        v_subtotal := round(v_qty * v_price, 2);
        v_product_id := nullif(v_item ->> 'product_id', '')::bigint;

        insert into public.sale_items (sale_id, product_id, code, name, unit, price, qty, subtotal, mode)
        values (
            v_sale.id,
            v_product_id,
            v_item ->> 'code',
            coalesce(v_item ->> 'name', ''),
            v_item ->> 'unit',
            v_price,
            v_qty,
            v_subtotal,
            coalesce(v_item ->> 'mode', 'normal')
        );

        if v_product_id is not null then
            update public.products
            set stock = stock - v_qty
            where id = v_product_id;
        end if;
    end loop;

    return v_sale;
end;
$$;

